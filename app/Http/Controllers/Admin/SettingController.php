     * @return \Illuminate\Http\Response
     */
    public function index(Request $request)
    {
        return view('admin.settings.form')->with([
            'settings' => Setting::where('status', 1)
                ->whereNotIn('code', self::socialSettingCodes())
                ->get(),
        ]);
    }

